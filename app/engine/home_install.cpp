std::string code_text(unsigned int code) {
    char text[24];
    std::snprintf(text, sizeof(text), "2%03u-%04u", R_MODULE(code), R_DESCRIPTION(code));
    return text;
}

bool is_installed() {
    if (R_FAILED(nsInitialize())) return false;
    s32 count = 0;
    const bool installed = R_SUCCEEDED(nsCountApplicationContentMeta(kTitleId, &count)) && count > 0;
    nsExit();
    return installed;
}

Outcome uninstall() {
    Result rc = nsInitialize();
    if (R_FAILED(rc)) return failure("abrir el servicio ns", rc);
    rc = nsDeleteApplicationCompletely(kTitleId);
    nsExit();
    if (R_FAILED(rc)) return failure("quitar el título", rc, "Si ya no estaba instalado, no hay nada que quitar.");
    Outcome done;
    done.ok = true;
    return done;
}

Outcome install(Progress progress) {
    constexpr int kSteps = 6;
    report(progress, "Leyendo el nombre y el icono del NRO", 1, kSteps);
    std::vector<u8> nacp_bytes, icon;
    if (!read_nro_assets(nacp_bytes, icon))
        return failure("leer el NRO", 0, "No se pudo leer el nombre y el icono de sdmc:/switch/pokenx/pokenx.nro. El acceso arranca ese archivo, así que debe estar ahí.");
    NacpStruct nacp;
    std::memcpy(&nacp, nacp_bytes.data(), sizeof(nacp));
    patch_nacp(nacp, kTitleId);
    std::vector<homenca::File> exefs_files;
    if (!read_exefs(exefs_files)) return failure("leer el programa del acceso", 0, "El programa incluido en el NRO no tiene el formato esperado.");

    report(progress, "Derivando la clave de las cabeceras", 2, kSteps);
    Result rc = splCryptoInitialize();
    if (R_FAILED(rc)) return failure("abrir el servicio spl", rc, "La consola no dejó usar su servicio de claves desde este programa.");
    u8 kek[0x10];
    rc = splCryptoGenerateAesKek(kHeaderKekSource, 0, 0, kek);
    if (R_SUCCEEDED(rc)) rc = splCryptoGenerateAesKey(kek, kHeaderKeySource, g_header_key);
    if (R_SUCCEEDED(rc)) rc = splCryptoGenerateAesKey(kek, kHeaderKeySource + 0x10, g_header_key + 0x10);
    splCryptoExit();
    if (R_FAILED(rc)) return failure("derivar la clave", rc, "La consola no pudo generar la clave de las cabeceras NCA.");

    report(progress, "Creando el contenido del acceso", 3, kSteps);
    const homenca::Crypto crypto{sha256_callback, encrypt_header_callback};
    const std::string path = kNroPath;
    std::vector<homenca::File> program_romfs, control_romfs;
    program_romfs.push_back({"nextNroPath", homenca::Bytes(path.begin(), path.end())});
    program_romfs.push_back({"nextArgv", homenca::Bytes(path.begin(), path.end())});
    control_romfs.push_back({"control.nacp", homenca::Bytes(reinterpret_cast<const u8*>(&nacp), reinterpret_cast<const u8*>(&nacp) + sizeof(nacp))});
    control_romfs.push_back({"icon_AmericanEnglish.dat", icon});
    const homenca::Title title = homenca::build_title(crypto, kTitleId, homenca::build_pfs0(exefs_files), program_romfs, control_romfs);

    rc = ncmInitialize();
    if (R_FAILED(rc)) return failure("abrir el servicio ncm", rc);
    Outcome outcome;
    NcmContentStorage storage;
    NcmContentMetaDatabase database;
    Service manager;
    bool have_storage = false, have_database = false, have_manager = false;
    const auto finish = [&](Outcome result) {
        if (have_manager) serviceClose(&manager);
        if (have_database) ncmContentMetaDatabaseClose(&database);
        if (have_storage) ncmContentStorageClose(&storage);
        ncmExit();
        nsExit();
        return result;
    };
    rc = nsInitialize();
    if (R_FAILED(rc)) {
        ncmExit();
        return failure("abrir el servicio ns", rc);
    }
    rc = open_application_manager(&manager);
    if (R_FAILED(rc)) return finish(failure("abrir el gestor de aplicaciones (ns)", rc));
    have_manager = true;

    report(progress, "Quitando una copia anterior del acceso", 4, kSteps);
    nsDeleteApplicationCompletely(kTitleId);  // "not found" on a first install is normal

    report(progress, "Escribiendo el contenido en la tarjeta SD", 5, kSteps);
    rc = ncmOpenContentStorage(&storage, NcmStorageId_SdCard);
    if (R_FAILED(rc)) return finish(failure("abrir el almacén de la tarjeta SD (ncm)", rc, "¿Hay una tarjeta SD insertada y con espacio?"));
    have_storage = true;
    for (const homenca::Nca* nca : {&title.meta, &title.program, &title.control}) {
        rc = write_content(&storage, *nca);
        if (R_FAILED(rc)) return finish(failure("escribir un contenido (ncm)", rc, "No se pudo escribir en la tarjeta SD."));
    }
    rc = ncmOpenContentMetaDatabase(&database, NcmStorageId_SdCard);
    if (R_FAILED(rc)) return finish(failure("abrir la base de contenidos (ncm)", rc));
    have_database = true;
    NcmContentMetaKey key;
    std::memset(&key, 0, sizeof(key));
    key.id = kTitleId;
    key.version = 0;
    key.type = NcmContentMetaType_Application;
    key.install_type = NcmContentInstallType_Full;
    rc = ncmContentMetaDatabaseSet(&database, &key, title.meta_record.data(), title.meta_record.size());
    if (R_SUCCEEDED(rc)) rc = ncmContentMetaDatabaseCommit(&database);
    if (R_FAILED(rc)) return finish(failure("guardar el registro de contenido (ncm)", rc));

    report(progress, "Registrando la aplicación en HOME", 6, kSteps);
    ContentStorageRecord record;
    std::memset(&record, 0, sizeof(record));
    record.key = key;
    record.storage_id = NcmStorageId_SdCard;
    rc = push_application_record(&manager, kTitleId, record);
    if (R_FAILED(rc)) return finish(failure("registrar la aplicación (ns)", rc));
    invalidate_control_cache(&manager, kTitleId);  // only refreshes the icon; the title exists either way

    outcome.ok = true;
    return finish(outcome);
}

